describe("guessMenuCategory", () => {
  for (const [category, names] of Object.entries(MENU)) {
    for (const name of names) {
      it(`${name} → ${category}`, () => {
        expect(guessMenuCategory(name)).toBe(category);
      });
    }
  }

  it("分からないものは null", () => {
    expect(guessMenuCategory("おまかせセット")).toBeNull();
    expect(guessMenuCategory("")).toBeNull();
  });

  it("全角・半角の違いを気にしない", () => {
    expect(guessMenuCategory("ﾋﾞｰﾙ")).toBe("ビール・チューハイ");
  });
});

describe("guessDrinkCategory", () => {
  it("ドリンクだけを返す", () => {
    expect(guessDrinkCategory("ハイボール")).toBe("ハイボール");
    expect(guessDrinkCategory("タン塩")).toBeNull();
    expect(guessDrinkCategory("店長のおすすめ")).toBeNull();
  });
});
