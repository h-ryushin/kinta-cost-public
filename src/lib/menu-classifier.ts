import { isDrinkCategory, type DrinkCategory, type MenuCategory } from "./categories";

/**
 * メニュー名から分類を推測する（D-041・D-045）。上から順に調べ、最初に当てはまったものにする。
 * 順番に意味がある：
 * - 「飲み放題ビール」を飲み放題、「タマゴスープ」「辛いクッパ」をスープ・クッパにするため、先に調べる
 * - ウイスキーの「〇〇ハイ」はハイボール、それ以外の「〇〇ハイ」（ウーロンハイ・緑茶ハイ）は焼酎で割る
 *   チューハイ。「ウーロンハイ」をソフトドリンクにしないよう、ソフトドリンクより先に調べる
 * - 「さくらユッケ」（牛）をおつまみ・刺身にするため、焼肉より先に調べる
 * - 「レモンサワー」を薬味（レモン）にしないよう、ドリンクを薬味より先に調べる
 * - 「生ビール」「生タマゴ」を刺身にしないよう、刺身は「生」ではなく「ユッケ」「刺」で調べる
 */
const RULES: [MenuCategory, RegExp][] = [
  ["飲み放題", /飲み放題|飲放/],
  ["コース", /コース/],
  ["テイクアウト", /テイクアウト|持ち帰り|持帰/],
  ["ボトル", /ボトル/],
  ["スープ・クッパ", /スープ|クッパ/],
  ["デザート", /アイス|デザート|シャーベット|プリン|杏仁/],
  ["ハイボール", /ハイボール|角ハイ|コークハイ|ジンジャーハイ|ウイスキー|ウィスキー/],
  // ビールとチューハイ・サワーは1つの分類（D-183）
  ["ビール・チューハイ", /サワー|酎ハイ|チューハイ|チュウハイ|ハイ$|ハイ[（(]|ビール|ビア|ノンアル/],
  ["焼酎・日本酒", /日本酒|焼酎|冷酒|熱燗|純米|吟醸|地酒|泡盛/],
  ["梅酒・ワイン・マッコリ", /ワイン|マッコリ|梅酒|果実酒|みかん酒|ゆず酒|あんず酒|カクテル|シャンパン|スパークリング/],
  ["ソフトドリンク", /ウーロン|烏龍|緑茶|お茶|ジュース|コーラ|ジンジャー|カルピス|ラムネ|ソーダ|ソフトドリンク|オレンジ|アップル|キッズ|お子様/],
  ["その他のドリンク", /ドリンク/],
  ["ご飯物", /ごはん|ご飯|ライス|ビビンバ|冷麺|麺|丼|おにぎり|雑炊|茶漬/],
  [
    "おつまみ・刺身・薬味",
    /ユッケ|刺身|刺し|タタキ|たたき|キムチ|ナムル|のり|海苔|えだまめ|枝豆|チャンジャ|もやし|キザミ|味ネギ|チーズ|ポテト|レモン|わさび|タマゴ|たまご|卵|ポン酢|薬味/,
  ],
  ["サラダ・焼野菜", /サラダ|サンチュ|野菜|エリンギ|しいたけ|椎茸|ニンニク|にんにく|玉ネギ|玉ねぎ|白ネギ|白ねぎ|かぼちゃ|ピーマン|とうもろこし/],
];

/** 焼肉（部位の名前で見分ける） */
const MEAT =
  /ホルモン|とんちゃん|ミノ|レバー|センマイ|ハチノス|シマチョウ|マルチョウ|ギアラ|ハツ|トントロ|豚|鶏|セセリ|せせり|ウインナー|ソーセージ|タン|カルビ|ロース|ハラミ|サガリ|ヒレ|ミスジ|イチボ|赤身|牛/;

/**
 * 焼肉の味付け。名前に「タレ」「辛味噌」があればタレ、「塩」があれば塩。
 * どちらもなければ、ネギ系とタンは塩（ネギ塩・タン塩が定番のため）、それ以外はタレにする。
 */
function meatCategory(name: string): MenuCategory {
  const tokumori = /特盛/.test(name);
  const tare = /タレ|たれ|味噌/.test(name) ? true : /塩/.test(name) ? false : !/タン|ネギ|ねぎ/.test(name);
  if (tokumori) return tare ? "特盛（タレ）" : "特盛（塩）";
  return tare ? "焼肉（タレ）" : "焼肉（塩）";
}

/** 当てはまる分類がなければ null */
export function guessMenuCategory(name: string): MenuCategory | null {
  const normalized = name.normalize("NFKC");
  const matched = RULES.find(([, pattern]) => pattern.test(normalized))?.[0];
  if (matched) return matched;
  return MEAT.test(normalized) ? meatCategory(normalized) : null;
}

/** ドリンクの分類だけを推測する。ドリンクと分からなければ null */
export function guessDrinkCategory(name: string): DrinkCategory | null {
  const guessed = guessMenuCategory(name);
  return guessed && isDrinkCategory(guessed) ? guessed : null;
}
