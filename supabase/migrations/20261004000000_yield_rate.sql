-- =====================================================================
-- 材料に「使える割合（歩留まり）」を足す（D-100）
--   掃除・筋取り・サク取りで減る分を、材料ごとに % で持つ。
--   例：タンスライス 4,800円/kg、使えるのが 80% → 実際は 6,000円/kg として原価を出す。
--   仕込み品の出来上がり量（D-079）でも表せるが、材料1つで済むものはこちらのほうが簡単。
-- =====================================================================

alter table public.ingredients
  add column yield_rate numeric(5, 2) not null default 100
    check (yield_rate > 0 and yield_rate <= 100);

comment on column public.ingredients.yield_rate is '使える割合（%）。掃除や下処理で減る分を引いたあとの割合（D-100）';
