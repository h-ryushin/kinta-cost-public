-- =====================================================================
-- オーナー（管理者）は1人だけにする（D-090）
--   お店のオーナーは1人。管理者が増えると、秘密レシピを見られる人も増えてしまう。
--   データベース側で1人までに制限し、画面の作りが変わっても守られるようにする。
-- =====================================================================

create unique index profiles_single_admin on public.profiles ((true)) where role = 'admin';

comment on index public.profiles_single_admin is '管理者（オーナー）は1人だけ（D-090）';
